export const units: Unit[] = seeds.map((s, i) => {
  const id = `u${String(i + 1).padStart(2, "0")}`;
  const [
    title,
    explanation,
    rule,
    example,
    translation,
    blocks,
    tip,
    error,
    correction,
    exception,
  ] = s.grammar;
  const grammar: Grammar = {
    id: `${id}-grammar`,
    title,
    explanation,
    rule,
    example,
    translation,
    blocks: blocks.split("|").map((b) => {
      const [text, role] = b.split(":");
      return { text, role };
    }),
    tip,
    error,
    correction,
    exception,
  };
  const phrases: Phrase[] = s.phrases.map((p, j) => {
    const [de, es, ...variants] = p.split("|");
    return {
      id: `${id}-p${j + 1}`,
      unit: id,
      de,
      es,
      variants,
      hint: rule,
      rule: grammar.id,
    };
  });
  return {
    id,
    number: i + 1,
    level: i < 3 ? "A0" : "A1",
    title: s.title,
    subtitle: s.subtitle,
    goals: s.goals.split("|"),
    previous: i ? [`u${String(i).padStart(2, "0")}`] : [],
    grammar,
    phrases,
    readings: [],
  };
});
export const phrases = units.flatMap((u) => u.phrases);
